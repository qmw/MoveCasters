// Generates src/ui/manifest.js: sprite base name -> frame count, from assets/0x72/frames.
import { readdirSync, writeFileSync } from 'node:fs';
const files = readdirSync('assets/0x72/frames').filter((f) => f.endsWith('.png'));
const m = {};
for (const f of files) {
  const r = f.match(/^(.*)_f(\d+)\.png$/);
  if (r) m[r[1]] = Math.max(m[r[1]] || 0, +r[2] + 1);
  else m[f.replace(/\.png$/, '')] = 0;
}
writeFileSync('src/ui/manifest.js', '// Generated by tools/manifest.js\nexport const SPRITES = ' + JSON.stringify(m) + ';\n');
console.log(Object.keys(m).length, 'sprites');
